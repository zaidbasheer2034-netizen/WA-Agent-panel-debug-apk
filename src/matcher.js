/** توحيد النص العربي: إزالة التشكيل وتوحيد الهمزات والتاء المربوطة */
function normalizeText(t) {
  return String(t || '')
    .toLowerCase()
    .replace(/[\u064B-\u065F\u0670]/g, '') // التشكيل
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ؤ/g, 'و')
    .replace(/ئ/g, 'ي')
    .replace(/ة/g, 'ه')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * يفحص نص الرسالة.
 * @returns {{matched: boolean, reason: string}}
 */
function matchIntent(raw, cfg) {
  const text = normalizeText(raw);
  if (text.length < 4) return { matched: false, reason: '' };

  // 1) كلمات المستخدم المخصصة لها الأولوية
  const kws = Array.isArray(cfg && cfg.keywords) ? cfg.keywords : [];
  for (const kw of kws) {
    const k = normalizeText(kw);
    if (k && text.includes(k)) return { matched: true, reason: 'كلمة مخصصة: ' + kw };
  }

  // 2) عبارة صريحة عن البحث عن مقدم خدمة
  if (STRONG_PHRASES.some((w) => text.includes(w))) {
    return { matched: true, reason: 'بحث صريح عن مقدم خدمة' };
  }

  // 3) طلب/حاجة + كلمة خدمة معاً
  const hasService = SERVICE_WORDS.some((w) => text.includes(w));
  const hasNeed = NEED_VERBS.some((w) => text.includes(w));
  if (hasService && hasNeed) {
    return { matched: true, reason: 'طلب أو سؤال عن خدمة' };
  }

  return { matched: false, reason: '' };
}

module.exports = { matchIntent, normalizeText, SERVICE_WORDS, NEED_VERBS, STRONG_PHRASES };
